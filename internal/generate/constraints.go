package generate

import (
	"fmt"
	"go/ast"
	"go/build/constraint"
	"go/parser"
	"go/token"
	"os/exec"
	"strings"
)

// Use this toolchain's platform names, including implicit filename constraints.
func buildPlatforms() (map[string]bool, error) {
	data, err := exec.Command("go", "tool", "dist", "list").Output()
	if err != nil {
		return nil, fmt.Errorf("go tool dist list: %w", err)
	}

	platforms := map[string]bool{}
	for _, pair := range strings.Fields(string(data)) {
		parts := strings.Split(pair, "/")
		platforms["os:"+parts[0]] = true
		platforms["arch:"+parts[1]] = true
	}

	return platforms, nil
}

func filenameCondition(name string, platforms map[string]bool) string {
	parts := strings.Split(strings.TrimSuffix(name, ".go"), "_")
	if len(parts) < 2 {
		return ""
	}

	last := parts[len(parts)-1]
	if platforms["arch:"+last] {
		if len(parts) > 2 && platforms["os:"+parts[len(parts)-2]] {
			return parts[len(parts)-2] + " && " + last
		}

		return last
	}
	if platforms["os:"+last] {
		return last
	}

	return ""
}

func fileCondition(file *ast.File, name string, platforms map[string]bool) (string, error) {
	var modern constraint.Expr
	var legacy constraint.Expr
	for _, group := range file.Comments {
		if group.Pos() >= file.Package {
			break
		}

		for _, comment := range group.List {
			line := comment.Text
			if !constraint.IsGoBuild(line) && !constraint.IsPlusBuild(line) {
				continue
			}

			expr, err := constraint.Parse(line)
			if err != nil {
				return "", fmt.Errorf("%s: %w", name, err)
			}
			if constraint.IsGoBuild(line) {
				modern = expr
			} else {
				legacy = andCondition(legacy, expr)
			}
		}
	}

	if modern == nil {
		modern = legacy
	}
	if suffix := filenameCondition(name, platforms); suffix != "" {
		expr, err := constraint.Parse("//go:build " + suffix)
		if err != nil {
			return "", err
		}

		modern = andCondition(modern, expr)
	}
	if modern == nil {
		return "", nil
	}

	return modern.String(), nil
}

func andCondition(a, b constraint.Expr) constraint.Expr {
	if a == nil {
		return b
	}
	if a.String() == b.String() {
		return a
	}

	return &constraint.AndExpr{X: a, Y: b}
}

func generatedByActorx(data []byte) bool {
	file, err := parser.ParseFile(token.NewFileSet(), "", data, parser.ParseComments|parser.PackageClauseOnly)
	if err != nil {
		return false
	}

	for _, group := range file.Comments {
		for _, comment := range group.List {
			if comment.Text == "// Code generated by actorx-gen. DO NOT EDIT." {
				return true
			}
		}
	}

	return false
}
